    throw "docker compose failed with exit code $LASTEXITCODE"
}

Wait-HttpOk -Name "API" -Url "http://127.0.0.1:$ApiPort/health" -TimeoutSeconds 180
Wait-HttpOk -Name "Website" -Url "http://127.0.0.1:$WebPort/health" -TimeoutSeconds 120

docker compose --project-name $ProjectName ps

Write-DeployLog "Deployment complete."
Write-DeployLog "Website: $WebPublicUrl"
Write-DeployLog "API: $ApiPublicUrl"
Write-DeployLog "Flutter API define: --dart-define=API_BASE_URL=$ApiPublicUrl/api"
Write-DeployLog "Flutter SignalR define: --dart-define=SIGNALR_HUB_URL=$SignalRPublicUrl"
